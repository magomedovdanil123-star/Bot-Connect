create table if not exists public.series_catalog (
  series_id integer primary key,
  title text not null,
  premise text not null,
  city text not null,
  profession text not null,
  bible jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.series_seasons (
  season_id integer primary key,
  series_id integer not null references public.series_catalog(series_id) on delete cascade,
  season_number integer not null,
  title text not null,
  plan jsonb not null default '[]'::jsonb,
  status text not null default 'draft',
  unique (series_id, season_number)
);

create table if not exists public.series_episodes (
  episode_id integer primary key,
  season_id integer not null references public.series_seasons(season_id) on delete cascade,
  episode_number integer not null,
  title text not null,
  synopsis text not null,
  script jsonb,
  status text not null default 'planned',
  unique (season_id, episode_number)
);

create table if not exists public.series_identity_anchors (
  id bigint generated by default as identity primary key,
  series_id integer not null references public.series_catalog(series_id) on delete cascade,
  character_key text not null,
  anchor jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  unique (series_id, character_key)
);

create table if not exists public.media_assets (
  id uuid primary key default gen_random_uuid(),
  fingerprint text not null unique,
  kind text not null check (kind in ('image', 'video', 'audio')),
  bucket text not null,
  object_path text not null,
  content_type text not null,
  size_bytes bigint not null default 0,
  project_id integer,
  scene_id integer,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists media_assets_project_scene_idx
  on public.media_assets (project_id, scene_id);

create table if not exists public.series_memory_snapshots (
  series_id integer primary key,
  bible jsonb not null default '{}'::jsonb,
  continuity jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.series_memory_events (
  id bigint generated by default as identity primary key,
  series_id integer not null,
  episode_id integer,
  event_type text not null,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists series_memory_events_series_idx
  on public.series_memory_events (series_id, created_at);

create table if not exists public.series_continuity (
  id bigint generated by default as identity primary key,
  series_id integer not null,
  entity_type text not null check (entity_type in ('character', 'location', 'world_rule', 'fact')),
  entity_key text not null,
  value jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  unique (series_id, entity_type, entity_key)
);

create table if not exists public.series_media_links (
  id bigint generated by default as identity primary key,
  series_id integer not null,
  episode_id integer,
  project_id integer,
  scene_id integer,
  asset_id uuid not null references public.media_assets(id) on delete cascade,
  created_at timestamptz not null default now()
);

create index if not exists series_media_links_lookup_idx
  on public.series_media_links (series_id, episode_id, project_id, scene_id);

create table if not exists public.telegram_horoscope_channels (
  chat_id bigint not null,
  connection_id integer not null,
  created_at timestamptz not null default now(),
  primary key (chat_id, connection_id)
);

create table if not exists public.horoscope_channel_profiles (
  connection_id integer primary key,
  channel_name text not null,
  category text not null default 'Horoscope',
  niche text not null,
  tone text not null,
  topics jsonb not null default '[]'::jsonb,
  formats jsonb not null default '[]'::jsonb,
  video_length integer not null default 45,
  hook_style text not null,
  target_audience text not null,
  visual_mode text not null default 'AUTO',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.horoscope_content_runs (
  id serial primary key,
  chat_id bigint not null,
  topic text not null,
  status text not null default 'generating',
  connection_ids jsonb not null default '[]'::jsonb,
  total_count integer not null default 0,
  completed_count integer not null default 0,
  failed_count integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.horoscope_idea_library (
  id serial primary key,
  category text not null,
  template text not null,
  format text not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.horoscope_content_items (
  id serial primary key,
  run_id integer not null references public.horoscope_content_runs(id) on delete cascade,
  sequence integer not null,
  connection_id integer not null,
  channel_title text not null,
  channel_config jsonb not null default '{}'::jsonb,
  topic text not null,
  idea text not null,
  format text not null,
  hook text not null,
  script_json jsonb not null,
  title text not null,
  description text not null,
  title_variants jsonb not null default '[]'::jsonb,
  keywords jsonb not null default '[]'::jsonb,
  tags jsonb not null default '[]'::jsonb,
  hashtags jsonb not null default '[]'::jsonb,
  visual_mode text not null default 'AUTO',
  visual_search_queries jsonb not null default '[]'::jsonb,
  visual_prompt text not null,
  stock_assets jsonb not null default '[]'::jsonb,
  stock_status text not null default 'pending',
  stock_error text,
  voiceover_text text not null,
  banner_id text,
  banner_text text,
  banner_position text,
  banner_start integer,
  banner_end integer,
  status text not null default 'ready',
  content_hash text not null,
  error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
