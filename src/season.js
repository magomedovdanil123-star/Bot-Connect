// рубрика дня недели — с неё начинается пошаговая сборка («⏭» — пропустить)
export const WEEK = { 1: 'ai', 2: 'stars', 3: 'novelty', 4: 'trend', 5: 'good', 6: 'stars', 0: 'good' };
export const WEEK_NAME = { 1: 'Технологии', 2: 'Звёзды', 3: 'Новинки', 4: 'Тренд дня', 5: 'Хорошие новости', 6: 'Итоги недели', 0: 'Хорошее за неделю' };

const MSK = d => new Date(d.toLocaleString('en-US', { timeZone: 'Europe/Moscow' }));
const dayNo = d => Math.floor((Date.UTC(d.getFullYear(), d.getMonth(), d.getDate()) - Date.parse(SEASON_START + 'T00:00:00Z')) / 864e5);
export function holidayOf(date = new Date()) {
  const d = MSK(date), m = d.getMonth() + 1, dd = d.getDate();
  if ((m === 10 && dd >= 25) || (m === 11 && dd <= 1)) return 'halloween';
  if ((m === 12 && dd >= 15) || (m === 1 && dd <= 10)) return 'newyear';
  return null;
}
/** План выпуска на дату: сезон, серия сюжета, происшествие, наряды, праздник, рубрика дня. */
export function seasonDay(date = new Date()) {
  const d = MSK(date), n = Math.max(0, dayNo(d)), season = Math.floor(n / SEASON_DAYS) + 1, day = n % SEASON_DAYS + 1, arc = ARCS[(season - 1) % ARCS.length];
  const beat = arc.beats[day - 1] || [], inBeat = Object.entries(GAG_OF_LINE).find(([k]) => beat.some(l => l.includes(k)))?.[1];
  const gag = inBeat ? null : GAG_ORDER[(n + season) % GAG_ORDER.length], holiday = holidayOf(date), H = HOLIDAY_LOOKS[holiday] || {};
  const look = { owl: { ...LOOKS.owl[n % LOOKS.owl.length], ...H.owl }, mole: { ...LOOKS.mole[n % LOOKS.mole.length], ...H.mole } };
  if (beat.some(l => /бабочк/.test(l))) look.mole.acc = 'bowtie';   // серия «главные ведущие носят бабочки»
  return { season, day, total: SEASON_DAYS, arc: arc.title, beat, gag, look, holiday, rubric: WEEK[d.getDay()], dayName: WEEK_NAME[d.getDay()], date: d.toLocaleDateString('ru-RU', { day: 'numeric', month: 'long' }) };
}
/** План на весь текущий сезон (для экрана «📅 Сезон»). */
export function seasonPlan(date = new Date()) {
  const cur = seasonDay(date), start = new Date(date.getTime() - (cur.day - 1) * 864e5);
  return Array.from({ length: SEASON_DAYS }, (_, i) => seasonDay(new Date(start.getTime() + i * 864e5)));
}
