// Сценарий-блог «разбор сайта» без нейросети. Хомяк-ведущий говорит живо: реакции, вопросы зрителю, юмор.
// Пять форматов выпуска, каждая строка — из нескольких вариантов, а содержание берётся с самого сайта
// (заголовок, разделы, кнопка, цифры — analyzeSite). Так выпуски не повторяются и подходят под любой новый сайт.
function rng(seed) { let x = (seed >>> 0) || 1; return () => ((x = (x * 1664525 + 1013904223) >>> 0) / 4294967296); }
const cut = (s, n) => { s = (s || '').replace(/[«»"]/g, '').trim(); if (s.length <= n) return s; const w = s.slice(0, n).split(' '); w.pop(); return w.join(' ') + '…'; };
const GENERIC = /^(помощь|о нас|о компании|контакты|faq|вопросы|новости|блог|войти|вход|меню|главная|документ|политик|условия использ)/i;

export const BLOG_FORMATS = { check: 'Проверка сайта', expect: 'Ожидание и реальность', reasons: '3 причины', steps: 'Пошагово', myths: 'Мифы' };

export function blogScript({ site, offer = null, facts = null, seed = Date.now(), format = null }) {
  const r = rng(seed), pick = a => a[Math.floor(r() * a.length) % a.length];
  const domain = (facts?.domain || site).replace(/^https?:\/\//, '').replace(/\/.*$/, '').replace(/^www\./, '');
  const brand = domain.split('.')[0].replace(/^./, c => c.toUpperCase());   // в крючке — имя сервиса без «.ru»: адрес в кадре показываем один раз
  const fmt = format && BLOG_FORMATS[format] ? format : pick(Object.keys(BLOG_FORMATS));
  const perks = (offer?.perks || []).slice(0, 3).map(p => p.replace(/[.!]+$/, ''));
  const promise = cut(facts?.h1 || facts?.desc, 70);
  const parts = (facts?.heads || []).filter(h => !GENERIC.test(h) && h.length <= 50).slice(0, 3).map(h => cut(h, 40).toLowerCase());
  const cta = facts?.ctas?.[0] && cut(facts.ctas[0], 30);
  const nums = (facts?.nums || []).slice(0, 2);
  const what = perks.length ? perks : parts;

  const greet = pick(['Привет, ребят! С вами Хомяк.', 'Всем привет, ребята! На связи Хомяк.', 'Привет, друзья! Это Хомяк, и у меня новый разбор.', 'Ребят, привет! Хомяк снова в студии.']);
  const explain = [
    pick(['Короче, рефералы — это люди, которых ты приглашаешь по своей ссылке.', 'Смотри: рефералы — это друзья, которых ты приглашаешь по своей ссылке.', 'Если по-простому: рефералы — это те, кого ты приглашаешь по своей ссылке.']),
    pick(['Они регистрируются, а ты получаешь процент с их результата.', 'Друг регистрируется — и часть дохода сервиса идёт тебе.', 'Человек пришёл по твоей ссылке — сервис делится с тобой.']),
  ];
  const visit = `${pick(['Заходим на', 'Открываем', 'Окей, идём на'])} ${domain} и смотрим, что там есть.`;
  const onSite = [
    ...(promise ? [pick([`На главной крупно: «${promise}».`, `Первое, что видишь: «${promise}».`])] : []),
    ...(what.length ? [what.length > 1 ? `${pick(['Что тут есть:', 'По разделам:', 'Внутри:'])} ${what.slice(0, -1).join(', ')} и ${what[what.length - 1]}.` : `${pick(['Главное тут:', 'Суть простая:'])} ${what[0]}.`] : []),
    ...(nums.length ? [`${pick(['И цифры на сайте:', 'Из цифр на странице:'])} ${nums.join(' и ')}.`] : []),
    ...(cta ? [pick([`Видишь кнопку «${cta}»? С неё всё и начинается.`, `Жмём «${cta}» — и регистрация занимает пару минут.`])] : [pick(['Регистрация занимает пару минут.', 'Чтобы начать, нужна только регистрация.'])]),
  ];
  const honest = [
    pick(['Но давай честно: быстрых миллионов здесь не будет.', 'Спойлер: это не кнопка «бабло».', 'Я, честно, сначала не поверил, что это работает.']),
    pick(['Доход растёт, если делиться ссылкой с теми, кому это реально нужно.', 'Работает, если советовать то, что людям правда пригодится.', 'Нужны время и нормальная аудитория — без этого никак.']),
  ];
  const link = `Ссылка на ${offer?.short || 'регистрацию'} — в описании под видео.`;
  const outro = pick(['Подписывайся, и разберём ещё больше способов заработка!', 'Подписывайся, дальше покажу, сколько получилось заработать!', 'Подписывайся — в следующем выпуске проверим ещё один сайт!']);

  let lines;
  if (fmt === 'check') lines = [greet, pick([`Сегодня проверю ${brand}: правда ли там можно заработать.`, `Сегодня разберём ${brand} — развод или реально рабочая штука?`]),
    pick(['Звучит заманчиво, но я сначала разберусь.', 'Окей, звучит красиво. Но давай копнём глубже.']), ...explain, visit, ...onSite, ...honest,
    pick(['Мой вердикт: попробовать стоит, если не ждать чудес.', 'Итог: инструмент рабочий, но всё решает твоя активность.']), link, outro];
  else if (fmt === 'expect') lines = [greet, pick(['Сегодня про заработок на рефералах: ожидание и реальность.', 'Все думают, что на рефералах деньги падают с неба. Давай проверим.']),
    pick(['Ожидание: скинул ссылку — и деньги сами полетели.', 'Ожидание: один пост — и ты миллионер.']), pick(['Реальность: работает, но не так, как в рекламе.', 'Реальность, как обычно, скромнее.']),
    ...explain, visit, ...onSite, honest[1], pick(['Так что ожидания — пониже, а действия — почаще.', 'Короче, чудес нет, но система рабочая.']), link, outro];
  else if (fmt === 'reasons') lines = [greet, pick([`Сегодня три причины присмотреться к ${brand}.`, 'Сегодня разберём три причины присмотреться к заработку на рефералах.']),
    ...explain, visit, `Первая причина — ${pick(['старт без вложений', 'начать можно с телефона', 'регистрация за пару минут'])}.`,
    `Вторая причина — ${what[0] ? cut(what[0], 34) : pick(['платят за реальный результат', 'понятные условия'])}.`, `Третья причина — ${pick(['доход растёт вместе с твоей аудиторией', 'можно совмещать с работой или учёбой'])}.`,
    ...onSite.slice(-1), honest[0], link, outro];
  else if (fmt === 'steps') lines = [greet, pick([`Сегодня покажу, как начать в ${brand} буквально за вечер.`, 'Сегодня пошагово: как начать зарабатывать на рекомендациях.']),
    ...explain, visit, ...onSite.slice(0, 2), `Первый шаг — ${cta ? 'жмём «' + cta + '»' : 'регистрируемся на сайте'}.`,
    `Второй шаг — ${pick(['выбираем, что будем рекомендовать', 'разбираемся, за что платят'])}.`, `Третий шаг — ${pick(['делимся ссылкой с теми, кому это нужно', 'рассказываем друзьям и подписчикам'])}.`,
    honest[1], link, outro];
  else lines = [greet, pick(['Сегодня разберём главные мифы про заработок на рефералах.', 'Про рефералы ходит куча мифов. Разбираем по-честному.']),
    'Первый миф — это сплошной развод.', ...explain, visit, ...onSite.slice(0, 2), 'Второй миф — нужно много подписчиков.', pick(['Начать можно и с друзей, и с одного поста.', 'На старте хватит знакомых, которым это реально нужно.']),
    'Третий миф — деньги придут сами.', honest[0], link, outro];
  return lines.join('\n');
}

