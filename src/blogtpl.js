// Сценарий-блог «разбор сайта» без нейросети: хомяк-ведущий здоровается, объясняет рефералы,
// показывает сайт (бот снимет его сам), честно говорит о плюсах и минусах и зовёт по ссылке.
// Каждая строка — из нескольких вариантов, чтобы выпуски не повторялись слово в слово.
const pick = (arr, r) => arr[Math.floor(r() * arr.length) % arr.length];
function rng(seed) { let x = (seed >>> 0) || 1; return () => ((x = (x * 1664525 + 1013904223) >>> 0) / 4294967296); }

export function blogScript({ site, offer = null, seed = Date.now() }) {
  const r = rng(seed), domain = site.replace(/^https?:\/\//, '').replace(/\/.*$/, '');
  const perks = (offer?.perks || []).slice(0, 3);
  const lines = [
    pick(['Привет, ребят! С вами Хомяк.', 'Всем привет, ребята! На связи Хомяк.', 'Привет, друзья! Это Хомяк, и у меня новый разбор.'], r),
    pick(['Сегодня я хочу разобраться, можно ли реально зарабатывать на рефералах.', 'Сегодня разберём, как зарабатывать в интернете на рекомендациях.', 'Сегодня проверю, работает ли заработок на рефералах на самом деле.'], r),
    pick(['Рефералы — это люди, которых ты приглашаешь по своей ссылке.', 'Смотри: рефералы — это друзья, которых ты приглашаешь по своей ссылке.'], r),
    pick(['Они регистрируются, а ты получаешь процент с их результата.', 'Друг регистрируется — и часть дохода сервиса идёт тебе.'], r),
    pick(['Звучит просто, но где этим заниматься?', 'Но где искать нормальный сервис, а не развод?'], r),
    `${pick(['Заходим на', 'Открываем'], r)} ${domain} и смотрим, что там есть.`,
    ...(perks.length ? perks.map((p, i) => `${i ? pick(['Ещё', 'А ещё'], r) + ' здесь' : 'Здесь'}: ${p.replace(/[.!]+$/, '').toLowerCase()}.`)
      : [pick(['Здесь можно рекомендовать карты, страховки и другие сервисы — и получать вознаграждение.', 'Здесь платят за рекомендации карт, страховок и других сервисов.'], r)]),
    pick(['Регистрация занимает пару минут.', 'Чтобы начать, нужна только регистрация.'], r),
    pick(['Честно скажу: быстрых миллионов здесь не будет.', 'Но давай честно: это не кнопка «бабло».'], r),
    pick(['Доход растёт, если делиться ссылкой с теми, кому это реально нужно.', 'Работает, если советовать то, что людям правда пригодится.'], r),
    `Ссылка на ${offer?.short || 'регистрацию'} — в описании под видео.`,
    pick(['Подписывайся, и разберём ещё больше способов заработка!', 'Подписывайся, дальше покажу, сколько получилось заработать!'], r),
  ];
  return lines.join('\n');
}
